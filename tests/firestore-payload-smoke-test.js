const fs = require('fs');
const vm = require('vm');
const path = require('path');
const writes = {};
const profile = { uid: 'customer-uid-001', username: 'CloneTester', usernameLower: 'clonetester', balance: 0, role: 'user', disabled: false };
const snap = { empty: false, docs: [{ id: 'clonetester', data: () => ({ ...profile }) }] };
const db = {
  collection(name) {
    return {
      doc(id) {
        return {
          async set(data) { writes[`${name}/${id}`] = structuredClone(data); },
          async update(data) { writes[`${name}/${id}`] = { ...(writes[`${name}/${id}`] || {}), ...data }; },
          async get() { return { exists: !!writes[`${name}/${id}`], data: () => writes[`${name}/${id}`] }; },
          onSnapshot() { return () => {}; }
        };
      },
      where(field, op, value) {
        return { limit() { return { async get() { return snap; } }; }, async get() { return snap; }, onSnapshot() { return () => {}; } };
      },
      async add(data) { const id = 'autogenerated'; writes[`${name}/${id}`] = structuredClone(data); return { id }; },
      async get() { return snap; }
    };
  }
};
const context = {
  console, Date, Math, Number, String, Object, Array, JSON, Promise,
  auth: { currentUser: { uid: 'customer-uid-001', email: 'clone@example.test' } },
  db,
  ADMIN_UID: 'admin-uid',
  normalizeUsername: v => String(v || '').trim().toLowerCase(),
  requireSignedIn: () => ({ uid: 'customer-uid-001' }),
  requireAdmin: () => { throw new Error('not admin'); },
  formatPrice: n => String(n)
};
vm.createContext(context);
for (const file of ['js/data/users.js', 'js/data/orders.js', 'js/data/cards.js', 'js/data/titlepurchases.js']) {
  vm.runInContext(fs.readFileSync(path.join(__dirname, '..', file), 'utf8'), context, { filename: file });
}
(async () => {
  await context.saveUserToDB({ ...profile, email: 'clone@example.test', facebook: '', createdAt: 'now', createdAtTs: 1, titleOverride: 'luyen-khi' });
  await context.saveOrderToDB({ id: 'ORD-1', username: 'CloneTester', status: 'pending', price: 100, origPrice: 100, account: 'RobloxPlayer', note: '', passwordProvidedSeparately: true, time: 'now', timestamp: 2, serviceId: 1, serviceName: 'Test', serviceCode: 'T-1', discountInfo: null, subOption: null, doneTime: null, doneMessage: null });
  await context.saveCardToDB({ id: 'CARD-1', username: 'CloneTester', type: 'Test', denom: 10000, serial: 'SERIAL', code: 'CODE', time: 'now', timestamp: 3, status: 'pending', note: '' });
  await context.saveTitlePurchaseToDB({ username: 'CloneTester', titleId: 'x', titleName: 'X', price: 100, origPrice: 100, renewalType: 'new', time: 'now', timestamp: 4, status: 'pending' });
  for (const key of ['users/clonetester', 'orders/ORD-1', 'cards/CARD-1', 'titlepurchases/autogenerated']) {
    const item = writes[key];
    if (!item) throw new Error('Missing Firestore write ' + key);
    if (key !== 'users/clonetester' && item.uid !== 'customer-uid-001') throw new Error('Missing UID on ' + key);
    if (key !== 'users/clonetester' && item.usernameLower !== 'clonetester') throw new Error('Missing usernameLower on ' + key);
  }
  console.log('PASS: User, order, card, title purchase all write UID + usernameLower.');
  console.log(JSON.stringify(Object.keys(writes), null, 2));
})().catch(err => { console.error(err); process.exitCode = 1; });
